import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, test } from 'vitest';
import { OUTLINES } from '../src/live/outlines.ts';

const root = join(import.meta.dirname, '../../..');
const web = join(root, 'apps/web/src/map');

describe('the server copy of the outlines (P7a D4)', () => {
  test('the same ids and paths as apps/web/src/map/<id>.json', () => {
    const files = readdirSync(web).filter((f) => f.endsWith('.json'));
    expect(files.length).toBeGreaterThan(20);
    const outlines = files.map((f) => [f.slice(0, -5), JSON.parse(readFileSync(join(web, f), 'utf8')).outline]);
    expect(OUTLINES).toEqual(Object.fromEntries(outlines));
  });

  test('its header carries the MIT notice of bacinger/f1-circuits', () => {
    const text = readFileSync(join(root, 'apps/server/src/live/outlines.ts'), 'utf8');
    const end = text.indexOf('\n\n// Generated by scripts/map-extract.ts');
    expect(end).toBeGreaterThan(0);
    const header = text.slice(0, end);
    const notice = readFileSync(join(root, 'data/third-party/f1-circuits/LICENSE.md'), 'utf8').trim();
    expect(header).toMatch(/^\/\/ .*\n\/\/\n\/\/ MIT License\n/);
    expect(header).toContain('// Copyright (c) 2019-2025 Tomislav Bacinger\n');
    expect(header.replace(/^\/\/ ?/gm, '')).toContain(notice);
  });
});
